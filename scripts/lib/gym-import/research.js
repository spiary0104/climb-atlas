// Regional research: the step BEFORE an import batch. One geographic section (a country, some of its states, or a bounding box
// inside one country) is researched into candidates with evidence, reconciled against Bouldeer, reviewed by a human, and only the
// accepted candidates are staged as an ordinary insert batch under import/batches/. See docs/import-workflow.md ("Regional research").
//
//   import/research/<YYYY-MM-DD-slug>/
//     section.json       scope + description (written by `research new`)
//     sources.json       source registry {S1: {kind, title, url, language, accessed}}
//     candidates.ndjson  one candidate per line (the research output)
//     reconcile.json/.md generated by `research reconcile` (deterministic; bound to the input hashes and the index)
//     review.json        the human decision for EVERY candidate
//
// Offline and read-only towards production: no network, no credentials, no write gate. Duplicate detection is the importer's own
// planBatch/match.js (thresholds and classification unchanged), plus review flags that are only ever STRICTER: they can send a
// candidate to review, never clear one. The staged batch then goes through validate/plan/import exactly like any other batch, and
// importer.js re-checks this provenance (verifyStagedBatch) before it will even plan it.
